import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { mockBackend } from './mock-backend'

test.beforeEach(async ({page})=>{await mockBackend(page)})

async function navigate(page: Page, name: string) {
  await expect(page.locator('main')).toBeVisible()
  const menu = page.getByRole('button', { name: 'Abrir menú' })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('link', { name, exact: true }).click()
}

test('register, assign and deliver update the dashboard and persist on reload', async ({ page }, testInfo) => {
  await page.goto('/')
  await navigate(page, 'Inscripciones')
  await page.getByRole('button', { name: 'Nueva inscripción' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva inscripción' })
  const code = `DEMO-E2E-${testInfo.project.name}`
  await dialog.getByLabel('Código del niño o niña').fill(code)
  await dialog.getByLabel('Nombre completo').fill('Niña de prueba E2E')
  await dialog.getByLabel('Fecha de nacimiento').fill('2019-04-12')
  await dialog.getByLabel('Nombre del apoderado/a').fill('Apoderada de prueba E2E')
  await dialog.getByRole('button', { name: 'Guardar inscripción' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Inscripción guardada' })).toBeVisible()
  await navigate(page, 'Asignación de regalos')
  await page.getByRole('textbox', { name: 'Buscar por nombre, código o apoderado' }).fill(code)
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'Asignar regalo', exact: true }).click()
  const assignment = page.getByRole('dialog', { name: 'Asignar regalo' })
  await assignment.getByLabel('Regalo a asignar').fill('Set de arte de prueba')
  await assignment.getByRole('button', { name: 'Asignar regalo', exact: true }).click()
  await expect(assignment).not.toBeVisible()
  await expect(page.locator('tbody tr')).toContainText('Pendiente')
  await navigate(page, 'Entregas')
  await page.getByRole('textbox', { name: 'Buscar por nombre, código o apoderado' }).fill(code)
  await page.getByRole('button', { name: 'Registrar entrega' }).click()
  const delivery = page.getByRole('dialog', { name: 'Registrar entrega' })
  await delivery.getByLabel('Fecha de entrega').fill('2026-11-12')
  await delivery.getByRole('button', { name: 'Confirmar entrega' }).click()
  await expect(delivery).not.toBeVisible()
  await expect(page.locator('tbody tr')).toContainText('Entregado')
  await expect(page.getByRole('button', { name: 'Registrar entrega' })).toHaveCount(0)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-deliveries.png`, fullPage: true })
  await navigate(page, 'Resumen')
  await expect(page.getByTestId('enrolled')).toHaveText('12.841')
  await expect(page.getByTestId('assigned')).toHaveText('11.521')
  await expect(page.getByTestId('pending')).toHaveText('3.180')
  await expect(page.getByTestId('delivered')).toHaveText('8.341')
  await page.reload()
  await expect(page.getByTestId('enrolled')).toHaveText('12.841')
  await expect(page.getByTestId('delivered')).toHaveText('8.341')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('duplicate registration is rejected without counting the child again', async ({ page }) => {
  await page.goto('/#inscripciones')
  await page.getByRole('button', { name: 'Nueva inscripción' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva inscripción' })
  await dialog.getByLabel('Código del niño o niña').fill('norte-0')
  await dialog.getByLabel('Nombre completo').fill('Niño de prueba duplicado')
  await dialog.getByLabel('Fecha de nacimiento').fill('2015-06-15')
  await dialog.getByLabel('Nombre del apoderado/a').fill('Apoderado de prueba')
  await dialog.getByRole('button', { name: 'Guardar inscripción' }).click()
  await expect(dialog.getByRole('alert')).toContainText('ya está inscrito')
  await dialog.getByRole('button', { name: 'Cancelar' }).click()
  await navigate(page, 'Resumen')
  await expect(page.getByTestId('enrolled')).toHaveText('12.840')
})
